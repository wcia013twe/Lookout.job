begin;
do $$
declare u uuid:=gen_random_uuid(); other_user uuid:=gen_random_uuid();
  key_hash text:=encode(extensions.digest(gen_random_uuid()::text,'sha256'),'hex');
  limited_hash text:=encode(extensions.digest(gen_random_uuid()::text,'sha256'),'hex');
  conn jsonb; first_batch jsonb; replay jsonb; app jsonb; approval jsonb;
  known_job text; rejected boolean; resume_id uuid:=gen_random_uuid();
begin
  insert into auth.users(id) values(u),(other_user);
  insert into public.profiles(user_id,facts,verified_at) values(u,'{"name":"Gateway test","email":"test@example.com"}',now()),(other_user,'{"name":"Other user"}',null);
  insert into public.resumes(id,user_id,name,reference_url) values(resume_id,u,'Test resume','https://example.com/resume.pdf');
  select id into known_job from public.jobs limit 1;
  conn:=public.manage_agent_connection(u,'connections.issue',jsonb_build_object('name','Test','tokenHash',key_hash,'scopes',jsonb_build_array('workspace:read','batches:write','drafts:write','activity:write','approvals:read')));
  if conn ? 'token_hash' then raise exception 'Hash leaked'; end if;
  if public.agent_dispatch(key_hash,'workspace.read','{}')->'profile'->'facts'->>'name' <> 'Gateway test' then raise exception 'Owner isolation failed'; end if;
  first_batch:=public.agent_dispatch(key_hash,'batches.publish',jsonb_build_object('eventKey','morning-test','label','Test morning','jobs',jsonb_build_array(jsonb_build_object('jobId',known_job))));
  replay:=public.agent_dispatch(key_hash,'batches.publish','{"eventKey":"morning-test","label":"Retry","jobs":[]}');
  if first_batch->'batch' <> replay->'batch' or first_batch->'items' <> replay->'items' then raise exception 'Batch replay not idempotent'; end if;
  app:=public.agent_dispatch(key_hash,'drafts.prepare',jsonb_build_object('jobId',known_job,'expectedRevision',-1,'draft',jsonb_build_object('questions','[]'::jsonb,'questionsReviewed',true,'resumeId',resume_id)));
  if app->>'status' <> 'Awaiting approval' or (app->>'revision')::int <> 1 then raise exception 'Draft transition failed'; end if;
  rejected:=false;
  begin perform public.agent_dispatch(key_hash,'drafts.prepare',jsonb_build_object('jobId',known_job,'expectedRevision',0,'draft','{}'::jsonb)); exception when sqlstate '40001' then rejected:=true; end;
  if not rejected then raise exception 'Stale draft accepted'; end if;
  approval:=public.agent_dispatch(key_hash,'approvals.read',jsonb_build_object('applicationId',app->>'id'));
  if approval->'approval' <> 'null'::jsonb then raise exception 'Unapproved snapshot returned'; end if;
  if app->'draft'->>'questionsReviewed' <> 'false' then raise exception 'Agent claimed human review'; end if;
  update public.applications set draft=jsonb_set(draft,'{questionsReviewed}','true') where id=(app->>'id')::uuid returning to_jsonb(applications) into app;
  perform set_config('request.jwt.claim.sub',u::text,true);
  perform public.approve_application((app->>'id')::uuid,(app->>'revision')::integer);
  perform set_config('request.jwt.claim.sub','',true);
  approval:=public.agent_dispatch(key_hash,'approvals.read',jsonb_build_object('applicationId',app->>'id'));
  if approval->'approval'->'snapshot'->'draft' <> app->'draft' then raise exception 'Approval snapshot mismatch'; end if;
  app:=public.agent_dispatch(key_hash,'drafts.prepare',jsonb_build_object('jobId',known_job,'expectedRevision',app->'revision','draft','{}'::jsonb));
  approval:=public.agent_dispatch(key_hash,'approvals.read',jsonb_build_object('applicationId',app->>'id'));
  if approval->'approval' <> 'null'::jsonb then raise exception 'Stale approval returned'; end if;

  if public.agent_dispatch(key_hash,'credentials.verify','{}')->>'name' <> 'Test' then raise exception 'Discovery failed'; end if;
  rejected:=false;
  begin perform public.agent_dispatch(key_hash,'resumes.read',jsonb_build_object('resumeId',resume_id)); exception when sqlstate '42501' then rejected:=true; end;
  if not rejected then raise exception 'Resume scope bypass'; end if;
  rejected:=false;
  begin perform public.agent_dispatch(key_hash,'batches.publish','{"eventKey":"malicious-test","label":"Bad","jobs":[{"canonicalUrl":"https://example.com/bad","employer":{"profile":{"name":"private"}}}]}'); exception when sqlstate '22023' then rejected:=true; end;
  if not rejected then raise exception 'Personal employer data published'; end if;
  update private.agent_connections set scopes=array_append(scopes,'resumes:read') where token_hash=key_hash;
  if public.agent_dispatch(key_hash,'resumes.read',jsonb_build_object('resumeId',resume_id))->>'id' <> resume_id::text then raise exception 'Owned resume unavailable'; end if;
  rejected:=false;
  begin perform public.agent_dispatch(key_hash,'resumes.read',jsonb_build_object('resumeId',gen_random_uuid())); exception when sqlstate 'P0002' then rejected:=true; end;
  if not rejected then raise exception 'Unknown resume accepted'; end if;
  perform public.manage_agent_connection(u,'connections.issue',jsonb_build_object('name','Limited','tokenHash',limited_hash,'scopes',jsonb_build_array('workspace:read')));
  rejected:=false;
  begin perform public.agent_dispatch(limited_hash,'batches.publish','{}'); exception when sqlstate '42501' then rejected:=true; end;
  if not rejected then raise exception 'Scope bypass'; end if;
  rejected:=false;
  begin perform public.manage_agent_connection(other_user,'connections.revoke',jsonb_build_object('id',conn->>'id')); exception when sqlstate 'P0002' then rejected:=true; end;
  if not rejected then raise exception 'Cross-owner revoke accepted'; end if;
  perform public.manage_agent_connection(u,'connections.revoke',jsonb_build_object('id',conn->>'id'));
  rejected:=false;
  begin perform public.agent_dispatch(key_hash,'workspace.read','{}'); exception when sqlstate '28000' then rejected:=true; end;
  if not rejected then raise exception 'Revoked key accepted'; end if;
  update private.agent_connections set expires_at=now()-interval '1 second' where token_hash=limited_hash;
  rejected:=false;
  begin perform public.agent_dispatch(limited_hash,'workspace.read','{}'); exception when sqlstate '28000' then rejected:=true; end;
  if not rejected then raise exception 'Expired key accepted'; end if;
end $$;
select 'gateway hosted isolation, idempotency, revision, revocation and expiry checks passed' as result;
rollback;
