import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
const result=await build({entryPoints:['lib/search/documents.mjs'],bundle:true,write:false,platform:'neutral',format:'esm',minify:true,legalComments:'inline'});
const license=await readFile('node_modules/js-yaml/LICENSE','utf8');
const output='/* js-yaml 5.3.0\n'+license+'\n*/\n'+'// Generated by scripts/build-search-documents.mjs; includes MIT js-yaml.\n'+result.outputFiles[0].text;
const path='supabase/functions/agent-gateway/search-documents.mjs';
if(process.argv.includes('--check')){if(await readFile(path,'utf8')!==output)throw Error('Search document bundle is stale');}else await writeFile(path,output);
