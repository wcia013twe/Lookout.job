import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {call, unwrap, rows} from './client.mjs';

export const metrics = ['execution_status','task_success','quality','active_seconds','tool_calls','wakes_used','reviewed','cost_coverage','cost_input_tokens','cost_cached_input_tokens','cost_output_tokens','cost_estimated_total_usd'];
const escape = x => String(x).replace(/[\\&%$#_{}~^]/g, c => ({'\\':'\\textbackslash{}','~':'\\textasciitilde{}','^':'\\textasciicircum{}'}[c] || '\\'+c));
const number = (x, digits=0) => typeof x === 'number' && Number.isFinite(x) ? x.toFixed(digits) : '--';
const bool = x => x === true || x === 1 ? 'Pass' : x === false || x === 0 ? 'Fail' : '--';
export function render(data, family) {
  const selected = data.rows.filter(r=>r.case.startsWith(family));
  const output = ['% Generated by scripts/evals/paper-tables.mjs; edit the JSON, not this file.'];
  // Keep versions separate and print each row's release; reused runs never merge.
  const groups = Map.groupBy(selected, r=>`${r.case}|${r.version}`);
  let index=0;
  for (const records of groups.values()) {
    const first=records[0];
    output.push('\\begin{table*}[t]','\\centering\\scriptsize','\\begin{tabular}{@{}rllrrrrrrl@{}}','\\toprule',
      'Run & Release & Condition & Success & Quality & Active (s) & Tools & Wakes & Reviewed & Execution \\\\', '\\midrule');
    for (const r of records) {
      const s=r.scores;
      output.push([escape(r.run),escape(r.release),escape(r.condition),bool(s.task_success),number(s.quality,3),number(s.active_seconds,1),number(s.tool_calls),number(s.wakes_used),s.reviewed===true||s.reviewed===1?'Yes':s.reviewed===false||s.reviewed===0?'No':'--',escape(s.execution_status??'--')].join(' & ')+' \\\\');
    }
    output.push('\\bottomrule','\\end{tabular}',`\\caption{${escape(first.case)} benchmark results. Version: ${escape(first.version)}. Columns match the Langfuse Eval Case \\& Run dashboard. Each row represents one trajectory; -- denotes unavailable data. Quality follows the declared case-specific grader; checkpoint observations are not independent samples.}`,`\\label{tab:${family.toLowerCase()}-results-${++index}}`,'\\end{table*}','');
  }
  if (!selected.length) output.push('% No measured rows available for this family.');
  return output.join('\n');
}
function list(resource,args) {
  const collected=[]; let cursor;
  do {
    const reply=call([resource,'list',...args,'--limit',resource==='scores'?'100':'1000',...(cursor?['--cursor',cursor]:[])]);
    collected.push(...rows(reply)); cursor=unwrap(reply).meta?.cursor;
  } while(cursor);
  return collected;
}
export function snapshot() {
  const observations=list('observations',['--environment','benchmark','--is-root-observation','--fields','core,basic,trace_context']);
  const roots=new Map();
  for (const o of observations) {
    if (!/^evaluate-(baseline|lookout)$/.test(o.name)) continue;
    const caseId=o.tags?.find(t=>t.startsWith('eval-case:'))?.slice(10);
    const run=o.tags?.find(t=>t.startsWith('eval-run:'))?.slice(9);
    if (!caseId || !/^(COM|JOB)\d+$/.test(caseId) || !run) continue;
    const entry={case:caseId,run:Number(run),condition:o.name.slice(9),version:o.version,release:o.release??'',traceId:o.traceId,scores:{}};
    if (roots.has(o.traceId)) throw Error('Duplicate common root: '+o.traceId);
    roots.set(o.traceId,entry);
  }
  const scores=list('scores',['--environment','benchmark','--fields','subject','--name',metrics.map(m=>'eval_v1_'+m).join(',')]);
  for (const s of scores) {
    const id=s.subject?.kind==='trace'?s.subject.id:s.subject?.traceId;
    const entry=roots.get(id); if (!entry) continue;
    const key=s.name.slice(8); if (!metrics.includes(key)) continue;
    if (Object.hasOwn(entry.scores,key)) throw Error('Duplicate score for '+id+' '+key);
    entry.scores[key]=s.value;
  }
  const records=[...roots.values()].sort((a,b)=>a.case.localeCompare(b.case,undefined,{numeric:true})||a.version.localeCompare(b.version)||a.release.localeCompare(b.release)||a.run-b.run||a.condition.localeCompare(b.condition));
  return {schemaVersion:1,retrievedAt:new Date().toISOString(),source:'Langfuse environment=benchmark; common evaluate-* roots only; no pilots or verification traces',rows:records};
}
if (process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const target=resolve('docs/paper-tables'); mkdirSync(target,{recursive:true});
  const data=process.argv.includes('--refresh')?snapshot():JSON.parse(readFileSync(resolve(process.argv[2]||target+'/results.json'),'utf8'));
  if (process.argv.includes('--refresh')) writeFileSync(target+'/results.json',JSON.stringify(data,null,2)+'\n');
  const columns=['case','run','condition','version','release','traceId',...metrics];
  const csv=[columns.join(','),...data.rows.map(r=>columns.map(k=>'"'+String(r[k]??r.scores[k]??'').replaceAll('"','""')+'"').join(','))].join('\n')+'\n';
  writeFileSync(target+'/results.csv',csv);
  for (const family of ['COM','JOB']) writeFileSync(target+'/'+family.toLowerCase()+'-results.tex',render(data,family));
  console.log(`Rendered ${data.rows.length} trajectories across COM and JOB.`);
}
